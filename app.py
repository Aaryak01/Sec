# ---------------------------------------------------------------------------
# Open-ended questions — the ones with no clean structured intent behind them.
#
# "Is there anything else" carries no searchable words of its own, and "has the
# language gotten more urgent" is asking about wording across two filings.
# Neither can be answered by matching a single passage and filling a template,
# so both route to the model with several passages and the conversation so far
# (see _conversational_answer). Everything with something concrete to look up —
# a named metric, a superlative, a definition — keeps its existing route.
# ---------------------------------------------------------------------------

_VAGUE_FOLLOWUP_RE = re.compile(
    r"anything else|something else|what else|anything more|what other"
    r"|tell me more|say more|more detail|more about (that|this|it)"
    r"|^(go on|continue|elaborate|expand|keep going|and)\b"
    r"|^(is|are) there (any )?more"
    r"|^more\b",
    re.IGNORECASE,
)

_QUALITATIVE_COMPARISON_RE = re.compile(
    r"\bcompare\b|\bcomparison\b|\bcontrast\b|\bdiffer(s|ent|ence)?\b"
    r"|\bversus\b|\bvs\.?\b|\bchanged?\b|\bshift(ed|ing)?\b|\bevolv\w+"
    r"|\burgen\w+|\btone\b|\blanguage\b|\bwording\b|\bphras\w+|\bapproach\b"
    r"|\b(earlier|previous|prior|last year'?s?) filing\b|\byear over year\b",
    re.IGNORECASE,
)


def is_vague_followup(text_l: str) -> bool:
    """True for "anything else" / "tell me more" style messages, which only
    mean anything in the context of the turns before them."""
    return bool(_VAGUE_FOLLOWUP_RE.search(text_l))


def is_qualitative_comparison(text_l: str) -> bool:
    """True for comparisons about *wording* rather than numbers.

    A named metric or a superlative means the metrics path can answer exactly,
    so those keep their route — "compare Microsoft and Nvidia revenue in 2024"
    is a table lookup. This only claims comparisons with nothing numeric in
    them, which otherwise reach wants_metrics on the word "compare" alone and
    die there with "I don't have that financial data".
    """
    if detect_metric_column(text_l) or detect_superlative(text_l):
        return False
    return bool(_QUALITATIVE_COMPARISON_RE.search(text_l))


def is_open_ended(text_l: str) -> bool:
    return is_vague_followup(text_l) or is_qualitative_comparison(text_l)


# "The earlier filing" names one specific document — the one before whatever
# was just discussed — rather than describing a topic to search for. It gets
# resolved by date in _earlier_filing_comparison instead of by relevance.
_EARLIER_FILING_RE = re.compile(
    r"\b(earlier|previous|prior|preceding|last year'?s?|year before|year-ago)\b"
    r"[^.?!]{0,24}?\b(filing|filings|10-?k|10-?q|report|year|one|version|language|wording)\b"
    r"|\bprior year\b|\byear[- ]over[- ]year\b",
    re.IGNORECASE,
)


def refers_to_earlier_filing(text_l: str) -> bool:
    """True when the message points at the filing before the one just
    discussed, rather than at a topic."""
    return bool(_EARLIER_FILING_RE.search(text_l))


