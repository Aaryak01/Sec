GENERAL_EDUCATION_STARTERS = ["how do i", "how can i", "teach me", "help me"]
METRICS_TOPIC_WORDS = [
    "stock", "invest", "evaluate", "assess", "analyze", "analyse",
    "judge", "pick", "choose", "read filing", "read a filing", "reading",
    "filings", "tell if", "know if", "doing well",
]
TREND_TOPIC_WORDS = ["trend", "trends", "chart", "charts", "graph", "graphs", "line", "lines"]

# A handful of words that, if a typo lands close enough (edit distance 1),
# should still be recognized as the intended trigger word — e.g. "ready"
# for "read" in "help me explain how i can ready stock trends".
_EDU_KEY_WORDS = [
    "read", "reading", "trend", "trends", "stock", "invest", "investing",
    "evaluate", "assess", "analyze", "judge", "understand", "explain",
    "teach", "filing", "filings", "chart", "charts", "graph", "graphs",
    "interpret",
]


def _normalize_education_text(text_l: str) -> str:
    """Rebuilds the message with near-typos of key trigger words corrected,
    so pattern matching isn't thrown off by e.g. 'ready' for 'read'."""
    words = _WORD_RE.findall(text_l)
    normalized = []
    for w in words:
        if len(w) < 3 or w in _EDU_KEY_WORDS:
            normalized.append(w)
            continue
        best, best_dist = None, 2
        for key in _EDU_KEY_WORDS:
            if abs(len(key) - len(w)) > 2:
                continue
            d = _levenshtein(w, key, best_dist)
            if d < best_dist:
                best, best_dist = key, d
        normalized.append(best if best is not None else w)
    return " ".join(normalized)


def _classify_general_education(text_l: str, companies: list[str]):
    """Returns 'trend' (how to interpret a chart's shape), 'metrics' (which
    numbers to check and how), or None. Trend-reading is checked first since
    it's the more specific intent when both could plausibly match."""
    # Critical rule: a company named in THIS message always routes to
    # company-specific handling, and general education never falls back to
    # a remembered company from earlier turns — callers must pass the
    # current message's own (not carried-forward) company list here.
    if companies:
        return None
    normalized = _normalize_education_text(text_l)

    if any(p in normalized for p in TREND_READING_STANDALONE_PATTERNS):
        return "trend"
    has_starter = any(p in normalized for p in GENERAL_EDUCATION_STARTERS)
    if has_starter and any(t in normalized for t in TREND_TOPIC_WORDS):
        return "trend"

    if any(p in normalized for p in GENERAL_EDUCATION_STANDALONE_PATTERNS):
        return "metrics"
    if has_starter and any(t in normalized for t in METRICS_TOPIC_WORDS):
        return "metrics"

    return None


