# A handful of words that, if a typo lands close enough (edit distance <= 2),
# should still be recognized as a comparison request — e.g. "diffeence"
# (missing an 'r') for "difference".
_COMPARISON_KEY_WORDS = ["difference", "different"]


def _normalize_comparison_text(text_l: str) -> str:
    words = _WORD_RE.findall(text_l)
    normalized = []
    for w in words:
        if len(w) < 5 or w in _COMPARISON_KEY_WORDS:
            normalized.append(w)
            continue
        best, best_dist = None, 2
        for key in _COMPARISON_KEY_WORDS:
            if abs(len(key) - len(w)) > 2:
                continue
            d = _levenshtein(w, key, best_dist)
            if d < best_dist:
                best, best_dist = key, d
        normalized.append(best if best is not None else w)
    return " ".join(normalized)


def is_comparison_intent(text_l: str) -> bool:
    normalized = _normalize_comparison_text(text_l)
    if "difference between" in normalized or "different from" in normalized:
        return True
    return bool(re.search(r"\bvs\.?\b|\bversus\b", normalized))


def detect_definition_terms(text_l: str):
    """Like detect_definition_term, but returns every distinct term mentioned
    (in order of first appearance) instead of just the single best match —
    used to pull out both sides of a "X vs Y" comparison question."""
    found = {}
    for term, aliases in TERM_ALIASES.items():
        best_start, best_len = None, -1
        for alias in aliases:
            m = re.search(rf"\b{re.escape(alias)}\b", text_l)
            if m and len(alias) > best_len:
                best_start, best_len = m.start(), len(alias)
        if best_start is not None:
            found[term] = best_start
    return [term for term, _ in sorted(found.items(), key=lambda kv: kv[1])]


