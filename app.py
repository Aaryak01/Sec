def _strip_possessive(word: str) -> str:
    """"Tesla's" -> "tesla". Possessive forms otherwise slip past the
    company-name/stopword checks that are keyed on the bare word."""
    wl = word.lower()
    if wl.endswith("'s"):
        return wl[:-2]
    if wl.endswith("'"):
        return wl[:-1]
    return wl


def _extract_topic(question: str) -> str:
    """Pulls a short topic phrase out of the question for the response intro."""
    words = [_strip_possessive(w) for w in _WORD_RE.findall(question.lower())]
    topic_words = [w for w in words if w not in _TOPIC_STOPWORDS and len(w) > 1]
    if not topic_words:
        return "that"
    return " ".join(topic_words[:5])


# ---------------------------------------------------------------------------
# Broad, non-specific opening questions about a named company — "tell me
# everything about Apple", "give me an overview of Tesla". Unlike "now
# Microsoft" or "tell me about Apple" (where _extract_topic strips every word
# down to nothing, already handled below), "everything" and "overview" are
# real English words, not stopwords — without this check they fall straight
# through to _select_passages and get searched for literally, matching
# nothing in the filings. This is deliberately checked as explicit phrasing
# rather than folded into _TOPIC_STOPWORDS: stripping "everything"/"overview"
# as stopwords globally would blunt _extract_topic's topic label for
# unrelated questions that happen to contain them.
# ---------------------------------------------------------------------------

_BROAD_OVERVIEW_RE = re.compile(
    r"\btell me everything\b"
    r"|\ban overview\b|\boverview of\b"
    r"|\bwhat do you know about\b"
    r"|\bsummari[sz]e\b",
    re.IGNORECASE,
)


def is_broad_overview_request(text_l: str) -> bool:
    return bool(_BROAD_OVERVIEW_RE.search(text_l))


_NUMBER_RE = re.compile(
    r"\$\s?\d[\d,]*(?:\.\d+)?\s?(?:billion|million|thousand|B|M|K)?"  # dollar amounts
    r"|\d[\d,]*(?:\.\d+)?\s?%"  # percentages
)


def _bold_numbers(text: str) -> str:
    return _NUMBER_RE.sub(lambda m: f"**{m.group(0)}**", text)


_TOPIC_HISTORY_THRESHOLD = 0.12


def _topic_first_appearance_year(company: str, question: str, current_date: str):
    """Among this same company's OWN risk_factors filings, finds the earliest
    year where a passage matches this question reasonably well. Returns None
    if nothing else matches, or if the current filing already is the earliest."""
    mask = ((chunks_df["company"] == company) & (chunks_df["section"] == "risk_factors")).values
    idx = np.where(mask)[0]
    if len(idx) == 0:
        return None
    expanded = expand_query(question)
    q_vec = vectorizer.transform([expanded])
    sims = cosine_similarity(q_vec, tfidf_matrix[idx]).flatten()

    matched_dates = [
        chunks_df.iloc[idx[i]]["date"]
        for i, sim in enumerate(sims)
        if sim >= _TOPIC_HISTORY_THRESHOLD
    ]
    if not matched_dates:
        return None

    earliest_date = min(matched_dates)
    earliest_year = int(earliest_date[:4])
    current_year = int(current_date[:4])
    if earliest_year >= current_year:
        return None
    return earliest_year


def _reading_note(row, question: str, name: str):
    """'How to read this' aside — only shown when there's something concrete and
    checkable to point out: specifically, whether this same company has raised
    this same risk topic in an earlier filing. Returns None (no note) when
    there's nothing specific to say, or for non-risk sections."""
    if row["section"] != "risk_factors":
        return None

    first_year = _topic_first_appearance_year(row["company"], question, row["date"])
    if first_year is None:
        return None

    return (
        f"*This risk first appeared in {name}'s filings around {first_year} — "
        f"compare to that earlier filing to see if the language has gotten "
        f"more urgent or stayed essentially the same.*"
    )


def _search_response(name: str, row, topic: str, question: str, requested_year: int = None) -> str:
    snippet = _bold_numbers(_trim(row["text"]))
    form_label = _form_label(row["form"])
    intro = f"Here's what {name} disclosed about {topic} in their {form_label}:"
    citation = f"— Source: {name} {row['form']} filed {row['date']}"
    parts = [intro, snippet]

    # Be explicit when we couldn't honour the year that was asked for, rather
    # than quietly answering from a different filing than the one requested.
    if requested_year is not None and int(row["year"]) != requested_year:
        parts.append(
            f"*I don't have a {requested_year} filing from {name} covering this — "
            f"this passage is from their {int(row['year'])} filing instead.*"
        )

    note = _reading_note(row, question, name)
    if note:
        parts.append(note)
    parts.append(citation)
    return "\n\n".join(parts)


# ---------------------------------------------------------------------------
# AI-topic ranking fix: "Apple Intelligence" (the branded product) shares
# literal words with "artificial intelligence" (the general risk/tech topic),
# which let product-announcement passages in MD&A outrank the actual AI-risk
# discussion in Risk Factors purely on word overlap. For AI-related queries
# where no section was explicitly requested, we search both sections and
# discount matches driven by the branded product name.
# ---------------------------------------------------------------------------

_AI_QUERY_RE = re.compile(r"\bai\b|\bartificial intelligence\b|\bmachine learning\b", re.IGNORECASE)
_PRODUCT_NAME_RE = re.compile(r"\bapple intelligence\b", re.IGNORECASE)
AI_PRODUCT_NAME_PENALTY = 0.5
AI_SECTION_PREFERENCE_MARGIN = 0.20


def _is_ai_query(text: str) -> bool:
    return bool(_AI_QUERY_RE.search(text))


def _apply_product_name_penalty(hits, active: bool):
    """Halves the score of any passage whose match is driven by the branded
    product name "Apple Intelligence" rather than the general AI concept —
    only applied for general AI questions, not ones asking about the product
    itself. Re-sorts afterward since the penalty can reorder candidates."""
    if not active or not hits:
        return hits
    adjusted = [
        (score * AI_PRODUCT_NAME_PENALTY, row) if _PRODUCT_NAME_RE.search(row["text"]) else (score, row)
        for score, row in hits
    ]
    adjusted.sort(key=lambda t: t[0], reverse=True)
    return adjusted


def _company_section_mask(company: str, section: str, year: int = None):
    mask = (chunks_df["company"] == company) & (chunks_df["section"] == section)
    if year is not None:
        mask = mask & (chunks_df["year"] == year)
    return mask.values


def _best_hit_for_company(question: str, company: str, is_short_query: bool, forced_section: str = None, year: int = None):
    """Finds the single best-matching passage for one company, optionally
    scoped to a specific filing year.

    When a year is requested, fidelity to that year is preferred over
    fidelity to the section: not every company filed a Risk Factors section
    every year (a 10-Q often carries only MD&A), so rather than silently
    answering from a *different year*, we first try the same year's other
    section. Only if that year has nothing at all do we widen to all years."""
    result = _best_hit_for_company_scoped(question, company, is_short_query, forced_section, year)
    if result is None and year is not None and forced_section:
        result = _best_hit_for_company_scoped(question, company, is_short_query, None, year)
    if result is None and year is not None:
        result = _best_hit_for_company_scoped(question, company, is_short_query, forced_section, None)
    return result


def _best_hit_for_company_scoped(question: str, company: str, is_short_query: bool, forced_section: str, year: int):
    """Same matching logic as _best_hit_for_company, for one specific year
    (or all years, if year is None). When no section is forced and the
    question is about AI, both Risk Factors and MD&A are searched, and Risk
    Factors is preferred whenever its score is within
    AI_SECTION_PREFERENCE_MARGIN of the higher-scoring section — an AI
    question with an ambiguous section is more likely well-answered by Risk
    Factors specifically. Returns (score, row, section) or None.
    """
    ai_query = _is_ai_query(question)
    top_k = 5 if ai_query else 1

    if forced_section:
        mask = _company_section_mask(company, forced_section, year)
        hits = _apply_product_name_penalty(_search_pool(question, mask, top_k=top_k, aggressive=is_short_query), ai_query)
        if not hits:
            return None
        score, row = hits[0]
        return score, row, forced_section

    if not ai_query:
        mask = _company_section_mask(company, "mdna", year)
        hits = _search_pool(question, mask, top_k=1, aggressive=is_short_query)
        if not hits:
            return None
        score, row = hits[0]
        return score, row, "mdna"

    best_by_section = {}
    for sec in ("risk_factors", "mdna"):
        mask = _company_section_mask(company, sec, year)
        hits = _apply_product_name_penalty(_search_pool(question, mask, top_k=top_k, aggressive=is_short_query), True)
        if hits:
            best_by_section[sec] = hits[0]

    if not best_by_section:
        return None
    if "risk_factors" in best_by_section and "mdna" in best_by_section:
        risk_score, risk_row = best_by_section["risk_factors"]
        mdna_score, mdna_row = best_by_section["mdna"]
        top_score = max(risk_score, mdna_score)
        if top_score > 0 and risk_score >= top_score * (1 - AI_SECTION_PREFERENCE_MARGIN):
            return risk_score, risk_row, "risk_factors"
        if mdna_score >= risk_score:
            return mdna_score, mdna_row, "mdna"
        return risk_score, risk_row, "risk_factors"
    sec, (score, row) = next(iter(best_by_section.items()))
    return score, row, sec


def _low_confidence_message(name, topic: str) -> str:
    """Honest 'nothing solid found' response — used instead of presenting a
    weak/irrelevant TF-IDF match as if it were a confident answer."""
    where = f"{name}'s filings" if name else "the filings I have"
    if topic == "that":
        return (
            f"I'm not sure what specifically you'd like to know about {where.rstrip('.')} "
            f"— try naming a topic, like risk factors, a specific metric, or a recent filing."
        )
    return (
        f"I couldn't find a passage specifically about {topic} in {where}. "
        f"This might mean it's not something they've substantially addressed, "
        f"or try rephrasing — for example searching for a more specific term "
        f"related to {topic}."
    )


LOW_CONFIDENCE_MESSAGE = (
    "I'm not sure what you're asking. Try mentioning a specific company, "
    "metric, or financial term."
)


class Retrieval(NamedTuple):
    """What retrieval found, before anything decides how to word it."""
    passages: list      # (display_name, chunk_row) pairs; empty if nothing matched
    message: str        # what to show the user when passages is empty
    question: str       # the question after spell-correction
    topic: str
    year: int


def _select_passages(
    question: str, text_l: str, companies: list[str], prefer_risk_section: bool = False
) -> Retrieval:
    """Picks the most relevant filing passage(s) for a question.

    Split out from answering so the template formatter and the LLM path
    answer from exactly the same retrieved text.
    """
    corrected_question, low_confidence = _autocorrect_query(question)
    if low_confidence:
        return Retrieval([], LOW_CONFIDENCE_MESSAGE, question, None, None)
    question = corrected_question

    # A follow-up with no explicit risk/MD&A signal of its own stays scoped
    # to whichever section the last 1-2 turns were asking about. Otherwise,
    # leave the section unforced (None) so AI-topic queries can weigh both
    # sections via _best_hit_for_company — see the AI-topic ranking fix above.
    forced_section = "risk_factors" if (wants_risk_section(text_l) or prefer_risk_section) else None
    topic = _extract_topic(question)
    topic_word_count = 0 if topic == "that" else len(topic.split())
    is_short_query = topic_word_count <= SHORT_QUERY_MAX_WORDS
    threshold = SHORT_QUERY_RELEVANCE_THRESHOLD if is_short_query else SEARCH_RELEVANCE_THRESHOLD
    year = detect_year(text_l)
    if year is not None and companies:
        threshold = YEAR_SCOPED_RELEVANCE_THRESHOLD

    if len(companies) >= 2:
        # one passage per detected company, comparative feel
        results = []
        for company in companies:
            best = _best_hit_for_company(question, company, is_short_query, forced_section, year)
            if best and best[0] >= threshold:
                score, row, _sec = best
                results.append((COMPANY_DISPLAY.get(company, company.capitalize()), row))
        if not results:
            names = " and ".join(COMPANY_DISPLAY.get(c, c.capitalize()) for c in companies)
            return Retrieval([], _low_confidence_message(names, topic), question, topic, year)
        return Retrieval(results, None, question, topic, year)

    if len(companies) == 1:
        company = companies[0]
        name = COMPANY_DISPLAY.get(company, company.capitalize())
        best = _best_hit_for_company(question, company, is_short_query, forced_section, year)
        if best is None or best[0] < threshold:
            return Retrieval([], _low_confidence_message(name, topic), question, topic, year)
        _, row, _sec = best
        return Retrieval([(name, row)], None, question, topic, year)

    # No company detected: get each company's single best-matching passage, then
    # rank those across companies — so results aren't dominated by one company
    # whose chunks simply happen to score highest overall. Show the single best.
    per_company_hits = []
    for company in COMPANY_ALIASES:
        best = _best_hit_for_company(question, company, is_short_query, forced_section, year)
        if best and best[0] >= threshold:
            score, row, _sec = best
            per_company_hits.append((score, row))
    if not per_company_hits:
        return Retrieval([], _low_confidence_message(None, topic), question, topic, year)
    per_company_hits.sort(key=lambda t: t[0], reverse=True)
    _, top_row = per_company_hits[0]
    name = COMPANY_DISPLAY.get(top_row["company"], top_row["company"].capitalize())
    return Retrieval([(name, top_row)], None, question, topic, year)


def _answer_from_passages(found: Retrieval, history: list = None) -> str:
    """Words an answer from already-retrieved passages.

    With an API key configured (see llm.py) the model writes it; with no key —
    or if the call fails — the template formatter does. Both read the same
    filing text, so the fallback is a differently worded answer rather than a
    less grounded one.
    """
    if llm.is_enabled():
        generated = llm.answer(found.question, found.passages, history)
        if generated:
            return generated

    blocks = [
        _search_response(name, row, found.topic, found.question, found.year)
        for name, row in found.passages
    ]
    return "\n\n---\n\n".join(blocks)


# ---------------------------------------------------------------------------
# Wider context for open-ended questions.
#
# _select_passages answers "which single passage best matches this question",
# which is the right retrieval for "what does Apple say about X". It's the
# wrong one for "has the language gotten more urgent" — that needs the same
# topic across several filing years — and for "anything else", which has no
# searchable words of its own and is really pointing at the previous turns.
# ---------------------------------------------------------------------------

MAX_CONTEXT_PASSAGES = 8
MAX_CONTEXT_COMPANIES = 3
PASSAGES_PER_COMPANY = 3
CONTEXT_HISTORY_TURNS = 4
# Wide enough that the per-year winners below are drawn from a real spread of
# filings rather than whichever year happens to dominate the top few hits.
CONTEXT_SEARCH_POOL = 60


def _retrieval_query(message: str, history) -> str:
    """What to actually search on.

    A vague follow-up contributes no usable search terms, so it inherits the
    topic of the turn it follows — otherwise "is there anything else" retrieves
    on the word "anything".
    """
    # A message that names its own subject searches on itself. An open-ended
    # follow-up that doesn't ("is it more urgent now", "anything else") carries
    # almost no searchable terms, so it inherits the topic of the turn it
    # follows — otherwise retrieval runs on the word "urgent" and returns
    # whichever passage happens to use it.
    if detect_companies(message) or not is_open_ended(message.lower()):
        return message
    # Walk back past any other open-ended turns — two "tell me more"s in a row
    # would otherwise leave us searching on the word "more".
    for prior in _prior_user_messages(history, max_turns=CONTEXT_HISTORY_TURNS):
        if not is_open_ended(prior.lower()) and _extract_topic(prior) != "that":
            return f"{prior} {message}".strip()
    return message


def _company_passages_across_years(
    question: str, company: str, limit: int = PASSAGES_PER_COMPANY, forced_section: str = None
):
    """The best-matching passage from each filing year for one company, newest
    first — both ends of the comparison a "has this changed" question needs.

    Goes year by year through _best_hit_for_company rather than taking one wide
    pool, so the AI-topic section preference and the branded-product penalty
    still apply. Without that, an AI question pulls whichever section merely
    shares the most words — usually MD&A product talk rather than the risk
    disclosure actually being asked about.
    """
    rows = []
    for year in sorted(VALID_YEARS, reverse=True):
        best = _best_hit_for_company(question, company, False, forced_section, year)
        if best:
            rows.append(best[1])
        if len(rows) >= limit:
            break
    return rows


