STRONG_RISK_WORDS = {
    "severe", "severely", "significant", "significantly", "substantial",
    "substantially", "material", "materially", "critical", "critically",
    "catastrophic", "catastrophically", "adverse", "adversely",
    "devastating", "serious", "seriously", "extreme", "extremely",
    "threat", "threats", "threaten", "threatens", "threatened",
    "jeopardize", "jeopardized", "harm", "harmed", "harmful",
    "damage", "damaged", "damaging", "fail", "failure", "failures",
    "crisis", "volatile", "volatility", "unprecedented", "irreparable",
}
MILD_RISK_WORDS = {
    "may", "might", "could", "possible", "possibly", "potential",
    "potentially", "minor", "limited", "slight", "slightly", "moderate",
    "moderately", "somewhat", "uncertain", "uncertainty", "varies",
    "vary", "fluctuate", "fluctuation", "generally", "typically",
}
_WORD_RE = re.compile(r"[a-zA-Z']+")


def _risk_intensity(text: str) -> float:
    words = _WORD_RE.findall(text.lower())
    total = len(words) or 1
    strong = sum(1 for w in words if w in STRONG_RISK_WORDS)
    mild = sum(1 for w in words if w in MILD_RISK_WORDS)
    return (strong - mild) / total * 1000


def compute_risk_tone_scores(company: str):
    """Returns a DataFrame of (date, score) per filing, or None if there's no data."""
    sub = chunks_df[(chunks_df["company"] == company) & (chunks_df["section"] == "risk_factors")]
    if sub.empty:
        return None

    grouped = sub.groupby("date")["text"].apply(" ".join).reset_index()
    grouped["score"] = grouped["text"].apply(_risk_intensity)
    grouped["date"] = pd.to_datetime(grouped["date"])
    return grouped[["date", "score"]].sort_values("date").reset_index(drop=True)


