def _levenshtein(a: str, b: str, max_dist: int) -> int:
    if abs(len(a) - len(b)) > max_dist:
        return max_dist + 1
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        curr = [i] + [0] * len(b)
        row_min = curr[0]
        for j, cb in enumerate(b, 1):
            cost = 0 if ca == cb else 1
            curr[j] = min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost)
            row_min = min(row_min, curr[j])
        if row_min > max_dist:
            return max_dist + 1
        prev = curr
    return prev[-1]


def _find_close_vocab_match(word: str, max_dist: int = 2):
    """Returns (closest_vocab_word, distance) or (None, None) if nothing close."""
    candidates = [
        w for w in _VOCAB_UNIGRAMS
        if w[0] == word[0] and abs(len(w) - len(word)) <= max_dist
    ]
    best, best_dist = None, max_dist + 1
    for cand in candidates:
        d = _levenshtein(word, cand, best_dist - 1 if best_dist > 0 else 0)
        if d < best_dist:
            best, best_dist = cand, d
            if d <= 1:
                break
    return (best, best_dist) if best is not None else (None, None)


def _autocorrect_query(question: str):
    """Checks each content word against the filing vocabulary — conservatively.
    A word is only ever treated as a possible typo if it's NOT a common
    English word (common words like "whether" can be absent from the filing
    vocabulary just because TF-IDF strips them as stopwords, which doesn't
    make them typos) and the closest vocabulary match is a single character
    away (edit distance 1) — anything fuzzier is a coin flip, not a
    correction. When a word looks unrecognized but doesn't clear that bar
    (distance 2), we don't guess at what the user meant; the caller shows a
    generic low-confidence message instead. Returns (query_to_use,
    low_confidence: bool)."""
    skip_words = _TOPIC_STOPWORDS | set(QUERY_SYNONYMS.keys()) | ENGLISH_STOP_WORDS
    words = _WORD_RE.findall(question)
    corrected = list(words)
    changed = False
    for i, w in enumerate(words):
        # A possessive is never a typo, and left as-is it can fuzzy-match to
        # an unrelated shorter vocabulary word (e.g. "tesla's" ~ "tesla").
        wl = _strip_possessive(w)
        if len(wl) < 4 or wl in skip_words or wl in _VOCAB_UNIGRAM_SET:
            continue
        match, dist = _find_close_vocab_match(wl)
        if match is None:
            continue
        if dist <= 1:
            corrected[i] = match
            changed = True
        else:
            return question, True
    corrected_question = " ".join(corrected) if changed else question
    return corrected_question, False


