def _chart_series_selection(text_l: str):
    """Returns (series, title) where series is a list of (raw_column, display_label)."""
    has_gross = "gross margin" in text_l
    has_operating = "operating margin" in text_l
    has_margin_generic = "margin" in text_l
    has_revenue_growth = "revenue growth" in text_l or "growth rate" in text_l
    has_fcf = any(p in text_l for p in ["free cash flow", "fcf", "cash flow"])
    has_rd = any(p in text_l for p in ["r&d", "research and development"])
    has_revenue = any(p in text_l for p in ["revenue", "sales"])

    if has_gross and has_operating:
        return [("gross_margin", "Gross Margin %"), ("operating_margin", "Operating Margin %")], "Margins"
    if has_gross:
        return [("gross_margin", "Gross Margin %")], "Gross Margin"
    if has_operating:
        return [("operating_margin", "Operating Margin %")], "Operating Margin"
    if has_margin_generic:
        return [("gross_margin", "Gross Margin %"), ("operating_margin", "Operating Margin %")], "Margins"
    if has_revenue_growth:
        return [("revenue_growth", "Revenue Growth %")], "Revenue Growth"
    if has_fcf:
        return [("free_cash_flow_b", "Free Cash Flow ($B)")], "Free Cash Flow"
    if has_rd:
        return [("rd_pct", "R&D % of Revenue")], "R&D Spending"
    if has_revenue:
        return [("revenue_b", "Revenue ($B)")], "Revenue"
    # bare "growth" (or nothing more specific) — default to revenue over time
    return [("revenue_b", "Revenue ($B)")], "Revenue"


def _chart_unit(raw_col: str) -> str:
    return "$B" if raw_col in {"revenue_b", "free_cash_flow_b"} else "%"


