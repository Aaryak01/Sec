def route_message(message: str, history: list = None):
    """Returns a list of response parts: strings (markdown) and/or Path (chart image)."""
    text_l = message.lower().strip()

    if text_l in GREETINGS or len(text_l) < 3:
        return [HELP_MESSAGE]

    # `raw_companies` reflects only what THIS message names — used to gate
    # intents (a definition or general-education question shouldn't be
    # blocked just because a company came up earlier in the conversation).
    raw_companies = detect_companies(message)

    is_pure_definition_question = is_definition_intent(text_l, raw_companies)
    definition_term = None
    if is_pure_definition_question:
        if is_comparison_intent(text_l):
            comparison_terms = detect_definition_terms(text_l)
            if len(comparison_terms) >= 2:
                return [build_comparison_response(comparison_terms[0], comparison_terms[1])]
        definition_term = detect_definition_term(text_l)
        if definition_term:
            definition = TERM_DEFINITIONS[definition_term]
            if definition_term in QUANT_FINANCE_TERM_KEYS:
                definition += QUANT_SCOPE_NOTE
            return [definition]

    edu_kind = _classify_general_education(text_l, raw_companies)
    if edu_kind == "trend":
        return [trend_reading_education_response()]
    if edu_kind == "metrics":
        return [general_education_response()]

    # From here on, a company-scoped follow-up ("what about their
    # financials", "artificial intelligence") should carry forward the last
    # company/section mentioned in the last 1-2 turns — but an explicit
    # company name in THIS message always wins and resets that context.
    companies = raw_companies
    if not companies and history:
        carried = _carry_forward_company(history)
        if carried:
            companies = [carried]
    carry_risk_section = bool(history) and _carry_forward_wants_risk_section(history)
    carry_stock_price = bool(history) and _carry_forward_wants_stock_price(history)

    if wants_investment_advice(text_l):
        company = companies[0] if companies else None
        return [INVESTMENT_DISCLAIMER + _suggestions(company)]

    if wants_future_prediction(text_l):
        return handle_future_prediction(message, text_l, companies)

    if wants_risk_tone(text_l):
        if not companies:
            return ["Which company's risk tone would you like to see? Try naming one, e.g. \"Show me Nvidia's risk tone over time.\""]
        company = companies[0]
        name = COMPANY_DISPLAY.get(company, company.capitalize())
        scores = compute_risk_tone_scores(company)
        if scores is None:
            return [f"I don't have risk factors data for {name}." + _suggestions()]
        chart_path = risk_tone_chart_path(company, scores)
        summary = risk_tone_summary(company, scores)
        return [chart_path, summary]

    # Must come before wants_chart(): "show me X's stock price trend"
    # contains "trend", which would otherwise trip wants_chart() and land in
    # handle_chart()'s revenue-growth fallback (no metric phrase in
    # _chart_series_selection matches "stock price") — silently substituting
    # a different metric for the one actually asked about.
    if wants_stock_price(text_l):
        return handle_stock_price(text_l, companies, history)

    # A vague follow-up after a stock price question has none of
    # STOCK_PRICE_PATTERNS' words for wants_stock_price() above to match on
    # its own — carry the topic forward the same way company/risk-section
    # context already carries. Three shapes this takes: a chart follow-up
    # ("make a graph of it"), a bare company-name reply to
    # handle_stock_price's own "which company's stock price...?" clarifying
    # question ("Tesla's" — names a company but, once stopwords/the company
    # name are stripped, has no topic left, which _extract_topic flags as
    # "that" and would otherwise fall into the general company-overview
    # branch further down), and a comparison follow-up ("now compare it to
    # Apple" — no "stock" word of its own, and "compare" is itself one of
    # METRICS_INTENT_PATTERNS, so without this check it falls straight into
    # wants_metrics()'s generic revenue/margin overview instead. All three
    # gated on detect_metric_column(text_l) being None so an explicit
    # request for a different metric ("now graph revenue growth", "now
    # compare it to Apple's revenue growth") isn't overridden.
    if (
        carry_stock_price
        and detect_metric_column(text_l) is None
        and (
            wants_chart(text_l)
            or _wants_stock_comparison(text_l)
            or (companies and _extract_topic(message) == "that")
        )
    ):
        return handle_stock_price(text_l, companies, history)

    if wants_chart(text_l):
        return handle_chart(text_l, companies)

    # Open-ended questions have to be caught before wants_metrics: "compare the
    # earlier filing to see if the language got more urgent" trips the metrics
    # intent on the word "compare" alone and dies there with "I don't have that
    # financial data", even though nothing numeric was asked for. Comparisons
    # that DO name a metric were already excluded by is_qualitative_comparison,
    # so "compare Microsoft and Nvidia revenue in 2024" still lands on metrics.
    if is_open_ended(text_l):
        generated = _conversational_answer(message, companies, history)
        if generated:
            return [generated]

    if wants_metrics(text_l):
        return [handle_metrics(message, text_l, companies)]

    # A message with a company but no real topic left after stripping
    # stopwords/company names (e.g. "now Microsoft", "tell me about Apple")
    # isn't a searchable query, and neither is an explicit broad request
    # ("tell me everything about Apple", "give me an overview of Tesla") —
    # "everything"/"overview" are real words, not stopwords, so those would
    # otherwise reach _select_passages and get searched for literally,
    # matching nothing. Either way, a combined metrics + risk-topic overview
    # is a better default than searching for whatever's left.
    if companies and (_extract_topic(message) == "that" or is_broad_overview_request(text_l)):
        overview = _company_overview_response(companies[0])
        if overview:
            return [overview]

    # A "what is X" question whose X isn't in our dictionary. The model gets a
    # go with the conversation's context first — the term is often one the
    # filings themselves define — and we only say "outside my scope" if that
    # comes back empty.
    if is_pure_definition_question and definition_term is None:
        generated = _conversational_answer(message, companies, history)
        return [generated or OUT_OF_SCOPE_MESSAGE + _suggestions()]

    found = _select_passages(message, text_l, companies, prefer_risk_section=carry_risk_section)
    if found.passages:
        return [_answer_from_passages(found, history)]

    # Nothing cleared the relevance bar for a single passage. Before falling
    # back to "I'm not sure what you're asking", give the model the wider
    # context — several filings, plus the turns so far. A question we can't
    # match to one passage is often answerable from a few, or from what has
    # already been discussed.
    generated = _conversational_answer(message, companies, history)
    return [generated or found.message]


def _extract_text(content) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, str):
                parts.append(item)
            elif isinstance(item, dict) and "text" in item:
                parts.append(item["text"])
        return " ".join(parts)
    return str(content) if content is not None else ""


# ---------------------------------------------------------------------------
# Conversation memory: carries the last-mentioned company/section forward for
# 1-2 turns so short follow-ups ("what about their financials") don't need
# to re-name the company. Reads straight from Gradio's chat history rather
# than separate session state, so it's naturally scoped to each conversation.
# ---------------------------------------------------------------------------

CONTEXT_CARRY_FORWARD_TURNS = 2


def _prior_user_messages(history, max_turns: int = CONTEXT_CARRY_FORWARD_TURNS):
    """Yields the text of up to `max_turns` prior user messages, most recent
    first, excluding the current (last) message in history."""
    if not history:
        return
    turns = 0
    for entry in reversed(history[:-1]):
        if entry.get("role") != "user":
            continue
        yield _extract_text(entry.get("content"))
        turns += 1
        if turns >= max_turns:
            return


def _carry_forward_company(history):
    """Returns the most recently mentioned company from the last 1-2 user
    turns, or None if no company was mentioned in that window."""
    for text in _prior_user_messages(history):
        found = detect_companies(text)
        if found:
            return found[0]
    return None


def _carry_forward_wants_risk_section(history) -> bool:
    """True if the last 1-2 user turns were asking about risk factors —
    used so a follow-up like "what else?" stays scoped to that section."""
    for text in _prior_user_messages(history):
        if wants_risk_section(text.lower()):
            return True
    return False


def _carry_forward_wants_stock_price(history) -> bool:
    """True if the last 1-2 user turns were asking about stock price — used
    so a vague chart follow-up like "make a graph of it" stays scoped to
    stock price instead of falling into handle_chart()'s revenue-growth
    default (that message has no stock-specific words of its own for
    wants_stock_price() to match, the same way "what else?" has no risk-
    specific words of its own for wants_risk_section() to match)."""
    for text in _prior_user_messages(history):
        if wants_stock_price(text.lower()):
            return True
    return False


def user_submit(message, history):
    if not message or not message.strip():
        return history, ""
    history = history + [{"role": "user", "content": message}]
    return history, ""


def bot_respond(history):
    if not history or history[-1]["role"] != "user":
        return history
    user_message = _extract_text(history[-1]["content"])
    parts = route_message(user_message, history)
    for part in parts:
        if isinstance(part, Path):
            history = history + [{
                "role": "assistant",
                "content": {"path": str(part), "meta": {"_type": "gradio.FileData"}},
            }]
        else:
            history = history + [{"role": "assistant", "content": part}]
    return history


# ---------------------------------------------------------------------------
# Conversation history — persists chats per browser via storage.py, capped at
# 5 saved conversations per user. All persistence goes through the storage
# interface (save_conversation / get_conversations / get_conversation_messages
# / delete_conversation); nothing here talks to the database directly, so
# storage.py's backend can be swapped without touching any of this.
# ---------------------------------------------------------------------------

CONVERSATION_TITLE_MAX_LEN = 40


def _make_conversation_title(history: list) -> str:
    """Auto-generates a title from the first user message, ~40 chars."""
    for entry in history:
        if entry.get("role") == "user":
            text = _extract_text(entry.get("content")).strip()
            if not text:
                continue
            if len(text) > CONVERSATION_TITLE_MAX_LEN:
                text = text[:CONVERSATION_TITLE_MAX_LEN].rstrip() + "…"
            return text
    return "New chat"


def _format_conversation_choices(conversations: list):
    """Turns storage's [{id, title, updated_at}, ...] into Dropdown choices."""
    choices = []
    for c in conversations:
        date_str = datetime.fromtimestamp(c["updated_at"]).strftime("%b %d, %I:%M %p")
        choices.append((f"{c['title']} — {date_str}", c["id"]))
    return choices


def init_session(user_id: str, already_initialized: bool):
    """Bound to user_id_state's change event (fired by gr.BrowserState once
    it hydrates from localStorage — this fires on every page load, including
    refreshes, which is what makes it safe to use as the "session ready"
    signal instead of demo.load, which never delivers into gr.State here).
    Loads the most recently updated saved conversation, if any, so a page
    refresh doesn't lose history.

    Guarded to run exactly once per page load: this handler writes back to
    user_id_state (to persist a newly generated id), which re-triggers the
    same change event. Without the guard that second pass re-runs mid-session
    and overwrites `chatbot` with the last *saved* history — silently wiping
    a message the user has just sent but that hasn't been saved yet."""
    if already_initialized:
        return gr.skip(), gr.skip(), gr.skip(), gr.skip(), True

    if not user_id:
        user_id = uuid.uuid4().hex

    conversations = storage.get_conversations(user_id)
    if conversations:
        conversation_id = conversations[0]["id"]
        history = storage.get_conversation_messages(user_id, conversation_id)
    else:
        conversation_id = uuid.uuid4().hex
        history = []

    choices = _format_conversation_choices(conversations)
    dropdown_value = conversation_id if conversations else None
    return user_id, conversation_id, history, gr.update(choices=choices, value=dropdown_value), True


def save_after_exchange(user_id: str, conversation_id: str, history: list):
    """Auto-saves after each user/assistant exchange and refreshes the
    conversation list. The 5-conversation cap is enforced inside
    storage.save_conversation itself."""
    if not history:
        return gr.update()
    title = _make_conversation_title(history)
    storage.save_conversation(user_id, conversation_id, title, history)
    conversations = storage.get_conversations(user_id)
    choices = _format_conversation_choices(conversations)
    return gr.update(choices=choices, value=conversation_id)


def start_new_chat(user_id: str):
    """A fresh, unsaved conversation id — nothing is written to storage
    (and it won't count toward the 5-conversation cap) until the first
    message is actually sent."""
    conversation_id = uuid.uuid4().hex
    conversations = storage.get_conversations(user_id)
    choices = _format_conversation_choices(conversations)
    return conversation_id, [], gr.update(choices=choices, value=None)


def load_conversation(user_id: str, conversation_id: str):
    # The dropdown's `.change` event also fires on *programmatic* value
    # updates (e.g. when start_new_chat or delete_current_conversation set
    # its value to None to show "nothing selected") — without this guard,
    # that would clobber the conversation_id/chatbot state those functions
    # just set, with whatever stale value happened to be in the dropdown.
    if not conversation_id:
        return gr.skip(), gr.skip()
    history = storage.get_conversation_messages(user_id, conversation_id)
    return conversation_id, history


def delete_current_conversation(user_id: str, conversation_id: str):
    if conversation_id:
        storage.delete_conversation(user_id, conversation_id)
    conversations = storage.get_conversations(user_id)
    choices = _format_conversation_choices(conversations)
    if conversations:
        next_id = conversations[0]["id"]
        history = storage.get_conversation_messages(user_id, next_id)
    else:
        next_id = uuid.uuid4().hex
        history = []
    return next_id, history, gr.update(choices=choices, value=next_id if conversations else None)


