def _comparison_figsize(n_bars: int) -> tuple:
    """Scales figure width with the number of bars/companies being compared,
    so 2-3 bars don't render as tiny columns lost in a wide, mostly-empty
    figure. Width grows per bar within a sensible min/max range; height stays
    fixed since it's driven by labels/legend, not bar count."""
    width = max(4.5, min(9.5, 1.6 * n_bars + 2.5))
    return (width, 4.5)


