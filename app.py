def _year_drilldown_hint(company_name: str, year: int) -> str:
    """Suggests a concrete follow-up the router can actually answer. Phrased
    as the literal question to ask, naming the company and year, because a
    year-scoped search only fires when both are present in the message —
    a vague "go check that year's filing" leads to a dead end instead."""
    return (
        f"Ask \"what does {company_name}'s {year} filing say about risks\" "
        f"to see how they framed that year."
    )


def _describe_trend_shape(company_name: str, label: str, points: list) -> str:
    """Describes the actual shape of a metric's path across years, e.g. a dip
    and recovery vs. steady growth vs. a sustained decline."""
    if len(points) < 2:
        return ""

    first_y, first_v = points[0]
    last_y, last_v = points[-1]
    mid = points[1:-1]

    # locate the single largest deviation among the interior years, if any
    trough = min(points, key=lambda p: p[1])
    peak = max(points, key=lambda p: p[1])
    is_interior_trough = trough[0] not in (first_y, last_y) and trough[1] < first_v and trough[1] < last_v
    is_interior_peak = peak[0] not in (first_y, last_y) and peak[1] > first_v and peak[1] > last_v

    if is_interior_trough:
        return (
            f"{company_name}'s {label} dipped in {trough[0]} before recovering "
            f"through {last_y}. A dip followed by a rebound often reflects a "
            f"temporary headwind — like slowing demand or currency effects — "
            f"rather than a structural decline. "
            + _year_drilldown_hint(company_name, trough[0])
        )
    if is_interior_peak:
        return (
            f"{company_name}'s {label} peaked in {peak[0]} before pulling back "
            f"through {last_y}. A spike followed by a pullback can mean a "
            f"one-time boost — a big deal, a demand surge — that didn't repeat, "
            f"rather than an ongoing problem. "
            + _year_drilldown_hint(company_name, peak[0])
        )
    if last_v > first_v:
        # check for consistent, monotonic-ish growth vs. choppy growth
        diffs = [points[i + 1][1] - points[i][1] for i in range(len(points) - 1)]
        if all(d >= 0 for d in diffs):
            return (
                f"{company_name}'s {label} climbed steadily from {first_y} to "
                f"{last_y} with no down years in between. Consistent, "
                f"multi-year growth like this is generally a healthier signal "
                f"than a single strong year — it suggests the trend is "
                f"structural rather than a one-off."
            )
        weakest = min(points, key=lambda p: p[1])[0]
        return (
            f"{company_name}'s {label} rose overall from {first_y} to {last_y}, "
            f"but not in a straight line. Choppy, uneven growth can mean the "
            f"business is more exposed to factors outside its control. "
            + _year_drilldown_hint(company_name, weakest)
        )
    if last_v < first_v:
        diffs = [points[i + 1][1] - points[i][1] for i in range(len(points) - 1)]
        if all(d <= 0 for d in diffs):
            return (
                f"{company_name}'s {label} declined every year from {first_y} "
                f"to {last_y}. A sustained multi-year decline is a stronger "
                f"signal than a single down year — worth checking whether it's "
                f"specific to this company or affecting the whole industry."
            )
        weakest = min(points, key=lambda p: p[1])[0]
        return (
            f"{company_name}'s {label} fell overall from {first_y} to {last_y}, "
            f"with some ups and downs along the way. The decline may be "
            f"concentrated in one or two bad years rather than spread evenly. "
            + _year_drilldown_hint(company_name, weakest)
        )
    return (
        f"{company_name}'s {label} stayed roughly flat from {first_y} to "
        f"{last_y}. A flat trend can suggest a mature, stable business — not "
        f"necessarily bad, but worth checking whether competitors grew faster "
        f"over the same period."
    )


def handle_chart(text_l: str, companies: list[str]):
    series, title_metric = _chart_series_selection(text_l)
    label = _lower_title(title_metric)
    year = detect_year(text_l) or DEFAULT_YEAR

    # A single company clearly named alongside trend language ("show me
    # Google's revenue trend") must always get its own multi-year chart —
    # never the all-company comparison. Re-detecting directly from this
    # message's own text, rather than only trusting the `companies` the
    # caller narrowed down, is a second, independent guarantee of that: a
    # chart request is exactly the case where showing the wrong company (or
    # everyone at once) instead of the one actually asked about is most
    # visible and most confusing, so this doesn't rely on upstream state
    # alone.
    named_here = detect_companies(text_l)
    if len(named_here) == 1:
        companies = named_here

    if len(companies) == 1:
        company = companies[0]
        name = COMPANY_DISPLAY.get(company, company.capitalize())
        path = company_metric_chart_path(company, series, title_metric)
        if path is None:
            return [f"I don't have {label} data for {name}." + _suggestions(company)]
        intro = f"Here's {name}'s {label} from FY {VALID_YEARS[0]} to FY {VALID_YEARS[-1]}:"

        raw_col, series_label = series[0]
        points = [(y, _raw_value(company, y, raw_col)) for y in VALID_YEARS]
        points = [(y, v) for y, v in points if v is not None]
        shape_note = _describe_trend_shape(name, label, points)

        parts = [intro, path]
        if shape_note:
            parts.append(shape_note)
        return parts

    if len(companies) >= 2:
        names = " vs. ".join(COMPANY_DISPLAY.get(c, c.capitalize()) for c in companies)
        path = comparison_chart_path(series, year, companies_subset=companies)
        if path is None:
            return [f"I don't have enough {label} data to chart that for {names}." + _suggestions()]
        intro = f"Here's {label} for {names} — FY {year}:"
        return [intro, path]

    # no company named: compare all 10
    path = comparison_chart_path(series, year, companies_subset=None)
    if path is None:
        return [f"I don't have enough {label} data to chart that." + _suggestions()]
    intro = f"Here's {label} across all 10 companies for FY {year}:"
    return [intro, path]


