def _filing_label(row) -> str:
    """How a filing gets referred to in prose: "Tesla's 10K filed 2024-01-29"."""
    name = COMPANY_DISPLAY.get(row["company"], str(row["company"]).capitalize())
    return f"{name}'s {row['form']} filed {row['date']}"


def _filing_identity_label(company: str, form: str, date: str) -> str:
    """Same as _filing_label, for callers that have (company, form, date)
    rather than a chunk row — used for the earlier filing before any of its
    passages have been picked."""
    name = COMPANY_DISPLAY.get(company, str(company).capitalize())
    return f"{name}'s {form} filed {date}"


def _anchor_filing(history, companies):
    """The filing the previous turn was answered from, as (question, row).

    Re-runs the same retrieval on the previous question rather than parsing the
    previous answer: once the model is writing the answers, the source line is
    prose and its format drifts, but retrieval is deterministic, so re-running
    it reproduces the exact row that turn was built from.
    """
    for prior in _prior_user_messages(history, max_turns=CONTEXT_HISTORY_TURNS):
        prior_companies = detect_companies(prior) or companies
        if not prior_companies:
            logger.info("anchor_filing: skipping prior turn %r — no company detected", prior[:60])
            continue
        found = _select_passages(prior, prior.lower(), prior_companies)
        if found.passages:
            row = found.passages[0][1]
            logger.info(
                "anchor_filing: resolved to %s %s %s (section=%s) from prior turn %r",
                row["company"], row["form"], row["date"], row["section"], prior[:60],
            )
            return prior, row
        logger.info(
            "anchor_filing: prior turn %r retrieved no passage (message=%r)",
            prior[:60], found.message,
        )
    logger.warning("anchor_filing: no anchor found in last %d turns", CONTEXT_HISTORY_TURNS)
    return None, None


def _previous_filing_identity(anchor_row):
    """(company, form, date) of the filing immediately before `anchor_row` —
    same company and section, same form type where one exists.

    Resolved by date rather than by relevance. "The earlier filing" names a
    specific document, and ranking candidate years by how well they match the
    question's words is what produced "there's no earlier filing to compare
    to" while a perfectly good prior-year 10-K sat in the corpus.
    """
    company = anchor_row["company"]
    section = anchor_row["section"]
    anchor_date = str(anchor_row["date"])

    earlier = chunks_df[
        (chunks_df["company"] == company)
        & (chunks_df["section"] == section)
        & (chunks_df["date"].astype(str) < anchor_date)
    ]
    if earlier.empty:
        logger.warning(
            "previous_filing_identity: no rows before %s for company=%r section=%r "
            "— check chunks_df['date'] dtype/format if this fires with a known-good corpus",
            anchor_date, company, section,
        )
        return None
    logger.info(
        "previous_filing_identity: %d candidate rows before %s for %s/%s",
        len(earlier), anchor_date, company, section,
    )

    # Prefer like for like — a 10-K's predecessor is the previous 10-K, not
    # whichever 10-Q happens to be closest in time.
    same_form = earlier[earlier["form"] == anchor_row["form"]]
    pool = same_form if not same_form.empty else earlier
    prev_date = pool["date"].astype(str).max()
    form = pool[pool["date"].astype(str) == prev_date].iloc[0]["form"]
    logger.info("previous_filing_identity: selected %s filed %s", form, prev_date)
    return company, form, prev_date


def _filing_passage_sample(
    company: str, form: str, date: str, section: str, question: str,
    limit: int = PASSAGES_PER_FILING_COMPARISON,
):
    """Up to `limit` passages from one specific filing's section.

    Ranked by relevance to `question` first — with a broad question like a
    tone comparison, that's mostly just breaking ties, since most of a risk
    section shares vocabulary with any risk-flavored query. If relevance
    matching returns fewer than `limit` (a narrow query, a short section),
    padded with the filing's remaining passages in document order, so the
    sample size doesn't silently shrink just because the query wording was a
    poor match — a tone read doesn't depend on query relevance the way a
    single-fact lookup does.
    """
    mask = (
        (chunks_df["company"] == company)
        & (chunks_df["form"] == form)
        & (chunks_df["date"].astype(str) == str(date))
        & (chunks_df["section"] == section)
    ).values
    total = int(mask.sum())
    if total == 0:
        logger.warning(
            "filing_passage_sample: zero chunks for %s %s %s/%s — identity must be wrong",
            company, form, date, section,
        )
        return []

    hits = _search_pool(question, mask, min(limit, total), aggressive=True)
    rows = [row for _, row in hits]

    if len(rows) < min(limit, total):
        seen = {(r["date"], str(r["text"])[:80]) for r in rows}
        for _, row in chunks_df[mask].iterrows():
            key = (row["date"], str(row["text"])[:80])
            if key in seen:
                continue
            rows.append(row)
            seen.add(key)
            if len(rows) >= min(limit, total):
                break

    logger.info(
        "filing_passage_sample: %s %s %s/%s -> %d/%d passages (%d by relevance, %d padded)",
        company, form, date, section, len(rows), total, len(hits), len(rows) - len(hits),
    )
    return rows


# ---------------------------------------------------------------------------
# Unchanged-sentence detection.
#
# The model was shown two passages, one per filing year, and asserted a tone
# difference by quoting the *same* sentence from each side — SEC boilerplate
# genuinely does carry over year to year unchanged, and a prompt instruction
# alone wasn't reliable at stopping the model from citing that repetition as
# evidence of change anyway. This computes the fact structurally instead of
# hoping the model notices: every sentence in each side is checked against
# every sentence on the other side, and any match gets an explicit note
# attached to that passage's document metadata (see llm.build_documents)
# saying so — a fact in the data the model is grounding on, not an instruction
# it has to remember to follow.
# ---------------------------------------------------------------------------

_NEAR_DUPLICATE_RATIO = 0.85
_MIN_SENTENCE_LEN = 25


def _normalize_sentence_text(s: str) -> str:
    s = str(s).strip().lower()
    s = re.sub(r"[‘’]", "'", s)
    s = re.sub(r"[“”]", '"', s)
    s = re.sub(r"[^a-z0-9' ]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _split_sentences(text: str) -> list[str]:
    raw = re.split(r"(?<=[.!?])\s+", str(text))
    return [s.strip() for s in raw if len(s.strip()) >= _MIN_SENTENCE_LEN]


def _sentences_near_duplicate(a: str, b: str) -> bool:
    """True if two sentences are the same claim in essentially the same
    words — exact after normalizing case/punctuation, or close enough (a
    prefix clause added, a word swapped) that quoting both as if they differed
    would be misleading."""
    na, nb = _normalize_sentence_text(a), _normalize_sentence_text(b)
    if not na or not nb:
        return False
    if na == nb:
        return True
    # Cheap length gate before the O(n*m) ratio call below.
    if abs(len(na) - len(nb)) > max(len(na), len(nb)) * 0.5:
        return False
    return difflib.SequenceMatcher(None, na, nb).ratio() >= _NEAR_DUPLICATE_RATIO


def _flag_unchanged_sentences(later_rows, earlier_rows, later_label: str, earlier_label: str):
    """Per-row notes flagging any sentence that recurs near-verbatim in the
    paired filing's sample. Returns (later_notes, earlier_notes), each a list
    the same length as the corresponding rows list, entries None where no
    match was found."""
    later_sentences = [(i, s) for i, row in enumerate(later_rows) for s in _split_sentences(row["text"])]
    earlier_sentences = [(i, s) for i, row in enumerate(earlier_rows) for s in _split_sentences(row["text"])]

    later_notes = [None] * len(later_rows)
    earlier_notes = [None] * len(earlier_rows)

    for li, ls in later_sentences:
        if later_notes[li] is not None:
            continue
        for ei, es in earlier_sentences:
            if not _sentences_near_duplicate(ls, es):
                continue
            snippet = ls if len(ls) <= 160 else ls[:157] + "..."
            later_notes[li] = (
                f"UNCHANGED — this sentence also appears, essentially word for "
                f"word, in {earlier_label}: \"{snippet}\" Do not cite this "
                f"sentence as evidence the language changed."
            )
            if earlier_notes[ei] is None:
                earlier_notes[ei] = (
                    f"UNCHANGED — this sentence also appears, essentially word "
                    f"for word, in {later_label}: \"{snippet}\" Do not cite "
                    f"this sentence as evidence the language changed."
                )
            break

    n_flagged = sum(1 for n in later_notes + earlier_notes if n)
    if n_flagged:
        logger.info(
            "flag_unchanged_sentences: %d/%d passages contain a sentence repeated "
            "verbatim across both filings",
            n_flagged, len(later_rows) + len(earlier_rows),
        )
    return later_notes, earlier_notes


def _earlier_filing_comparison(message: str, companies: list[str], history):
    """Samples the filing just discussed and the one before it, for a tone
    comparison rather than a single-passage topic match.

    Returns (passages, instruction), or (None, None) when the message isn't
    asking for that or there's no prior filing to pair with — in which case the
    caller falls back to ordinary context gathering.
    """
    if not refers_to_earlier_filing(message.lower()):
        logger.info("earlier_filing_comparison: message %r not recognized as an earlier-filing request", message[:70])
        return None, None
    prior_question, anchor = _anchor_filing(history, companies)
    if anchor is None:
        logger.warning("earlier_filing_comparison: giving up — no anchor filing to compare from")
        return None, None
    identity = _previous_filing_identity(anchor)
    if identity is None:
        logger.warning(
            "earlier_filing_comparison: giving up — anchor is %s %s %s but no earlier "
            "filing exists in the same company+section",
            anchor["company"], anchor["form"], anchor["date"],
        )
        return None, None
    earlier_company, earlier_form, earlier_date = identity

    query = prior_question or message
    later_rows = _filing_passage_sample(
        anchor["company"], anchor["form"], anchor["date"], anchor["section"], query
    )
    earlier_rows = _filing_passage_sample(
        earlier_company, earlier_form, earlier_date, anchor["section"], query
    )
    if not later_rows or not earlier_rows:
        logger.warning(
            "earlier_filing_comparison: giving up — sample came back empty "
            "(later=%d, earlier=%d rows)", len(later_rows), len(earlier_rows),
        )
        return None, None

    later_name = COMPANY_DISPLAY.get(anchor["company"], str(anchor["company"]).capitalize())
    earlier_name = COMPANY_DISPLAY.get(earlier_company, str(earlier_company).capitalize())
    later_label = _filing_label(anchor)
    earlier_label = _filing_identity_label(earlier_company, earlier_form, earlier_date)

    later_notes, earlier_notes = _flag_unchanged_sentences(later_rows, earlier_rows, later_label, earlier_label)
    passages = (
        [(later_name, row, note) for row, note in zip(later_rows, later_notes)]
        + [(earlier_name, row, note) for row, note in zip(earlier_rows, earlier_notes)]
    )
    instruction = COMPARE_FILINGS_INSTRUCTION.format(
        n_later=len(later_rows), later=later_label,
        n_earlier=len(earlier_rows), earlier=earlier_label,
    )
    logger.info(
        "earlier_filing_comparison: comparing %d passages from %s %s (%s) against "
        "%d passages from %s %s (%s)",
        len(later_rows), anchor["company"], anchor["form"], anchor["date"],
        len(earlier_rows), earlier_company, earlier_form, earlier_date,
    )
    return passages, instruction


def _gather_context_passages(message: str, companies: list[str], history, seed_passages=None):
    """Assembles the passages to hand the model for an open-ended question:
    several filing years per company in play, plus whatever the recent turns
    were answered from."""
    query = _retrieval_query(message, history)
    collected = list(seed_passages or [])

    # A question about risk should compare risk sections across years, not
    # whichever section happens to share the most words — for several companies
    # that's MD&A product talk, which reads as an answer but isn't one.
    forced_section = "risk_factors" if wants_risk_section(query.lower()) else None

    for company in companies[:MAX_CONTEXT_COMPANIES]:
        name = COMPANY_DISPLAY.get(company, company.capitalize())
        for row in _company_passages_across_years(query, company, forced_section=forced_section):
            collected.append((name, row))

    # Re-running retrieval on the earlier questions is what makes "compare the
    # earlier filing" work: it puts back the passage that turn was answered
    # from, without needing to persist anything between requests.
    #
    # Only for genuine follow-ups, though. When the message names its own
    # companies the user has changed subject, and dragging the previous
    # company's passages along actively misleads — asked to compare Meta and
    # Microsoft, the model read a leftover Tesla passage as the subject and
    # described the other two as "Tesla's competitors".
    if not detect_companies(message):
        for prior in _prior_user_messages(history, max_turns=CONTEXT_HISTORY_TURNS):
            prior_companies = detect_companies(prior) or companies
            if not prior_companies:
                continue
            collected.extend(_select_passages(prior, prior.lower(), prior_companies).passages)

    deduped, seen = [], set()
    for name, row in collected:
        key = (row["company"], str(row["date"]), str(row["text"])[:120])
        if key in seen:
            continue
        seen.add(key)
        deduped.append((name, row))
    return deduped[:MAX_CONTEXT_PASSAGES]


def _relevant_history(message: str, history):
    """The conversation so far — unless this message names companies the
    conversation wasn't about.

    An explicit subject change makes the earlier turns misleading rather than
    helpful: asked to compare Meta and Microsoft after several Tesla turns, the
    model kept opening with an apology about not finding Tesla in the documents.
    """
    named = set(detect_companies(message))
    if not named:
        return history
    prior = {
        company
        for text in _prior_user_messages(history, max_turns=CONTEXT_HISTORY_TURNS)
        for company in detect_companies(text)
    }
    if prior and not (named & prior):
        return history[-1:]
    return history


def _conversational_answer(message: str, companies: list[str], history, seed_passages=None):
    """Model-written answer for a message with no clean structured intent.

    Returns None when there's no API key, nothing could be gathered to ground
    on, or the call failed — so every caller can fall back to whatever it would
    have said otherwise.
    """
    if not llm.is_enabled():
        return None

    # "Compare the earlier filing" resolves to two specific documents, so it
    # gets exactly those two and an instruction to compare them — handing it
    # the usual spread of passages is what let the model wander off and claim
    # there was nothing to compare against.
    pair, instruction = _earlier_filing_comparison(message, companies, history)
    if pair:
        result = llm.answer(
            message, pair, _relevant_history(message, history), instruction,
            max_tokens=COMPARISON_MAX_TOKENS,
        )
        if result is None:
            logger.warning(
                "conversational_answer: earlier-filing pair was built (%d passages) but "
                "llm.answer returned None — the model call itself failed; see llm.py logs",
                len(pair),
            )
        return result

    passages = _gather_context_passages(message, companies, history, seed_passages)
    if not passages:
        return None
    return llm.answer(message, passages, _relevant_history(message, history))


_SENTENCE_START_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z\d\"'“‘(])")
_STARTS_CLEAN_CHARS = set('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"\'“‘(')


def _find_sentence_start(text: str, search_window: int = 400) -> int:
    """Returns the index of the first clean sentence start in `text` (0 if it
    already starts on one). Retrieved chunks are cut mid-sentence at the
    source, so this trims the ragged lead-in before a passage is shown."""
    if not text:
        return 0
    if text[0] in _STARTS_CLEAN_CHARS:
        return 0
    m = _SENTENCE_START_RE.search(text[:search_window])
    if m:
        return m.start()
    return 0


def _trim(text: str, limit: int = 800, hard_max: int = 1400) -> str:
    text = text.strip()

    # Start at a clean sentence boundary rather than mid-sentence.
    start = _find_sentence_start(text)
    text = text[start:].strip()

    if len(text) <= limit:
        return text

    # Prefer ending at the last complete sentence at or before `limit`.
    window = text[:limit]
    idx = max(window.rfind(". "), window.rfind(".\n"))
    if idx != -1 and idx >= 150:
        return window[: idx + 1].strip()

    # No good boundary yet — extend forward to the next sentence end instead
    # of cutting mid-sentence.
    idx_fwd = text.find(". ", limit)
    if idx_fwd != -1 and idx_fwd < hard_max:
        return text[: idx_fwd + 1].strip()

    # Last resort: no sentence boundary found within a reasonable range.
    return window.rsplit(" ", 1)[0] + " …"


