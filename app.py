# Below this cosine-similarity score, a "match" is treated as noise rather
# than a real answer. Short/generic queries (e.g. just "AI") get a higher bar
# since a couple of overlapping words can produce a deceptively nonzero score
# against totally unrelated passages.
SEARCH_RELEVANCE_THRESHOLD = 0.08
SHORT_QUERY_RELEVANCE_THRESHOLD = 0.08
SHORT_QUERY_MAX_WORDS = 2

# Naming a company AND a specific year points at essentially one document,
# so the bar for "is this passage relevant" should be lower than for an
# open-ended query against the whole corpus. Without this, a reasonable
# drill-down like "what does Apple's 2025 filing say about risks" gets
# rejected purely because a broad word like "risks" carries little TF-IDF
# weight inside the Risk Factors section, where it appears everywhere.
YEAR_SCOPED_RELEVANCE_THRESHOLD = 0.03

# How many extra times the user's own words are repeated relative to their
# expanded synonyms — a passage that only matches the synonyms and not the
# actual term the user typed should score lower than one that matches both.
ORIGINAL_TERM_WEIGHT = 2
SHORT_QUERY_ORIGINAL_TERM_WEIGHT = 3


def expand_query(question: str, aggressive: bool = False) -> str:
    tokens = _WORD_RE.findall(question.lower())
    weight = SHORT_QUERY_ORIGINAL_TERM_WEIGHT if aggressive else ORIGINAL_TERM_WEIGHT
    expanded = []
    for tok in tokens:
        # Drop the company name entirely — the search is already scoped to
        # that company's chunks, so matching on its own name just adds noise
        # (e.g. "Apple M1 Pro" mentions inflate scores for unrelated passages).
        if tok in _COMPANY_ALIAS_WORDS:
            continue
        # Only up-weight genuine content words (the actual topic terms) — not
        # generic question-framing words, which carry no topical signal.
        tok_weight = weight if tok not in _TOPIC_STOPWORDS else 1
        expanded.extend([tok] * tok_weight)
        expanded.extend(QUERY_SYNONYMS.get(tok, []))
    return " ".join(expanded) if expanded else question


def _search_pool(question: str, mask: np.ndarray, top_k: int, aggressive: bool = False):
    idx = np.where(mask)[0]
    if len(idx) == 0:
        return []
    expanded = expand_query(question, aggressive=aggressive)
    q_vec = vectorizer.transform([expanded])
    sims = cosine_similarity(q_vec, tfidf_matrix[idx]).flatten()
    order = sims.argsort()[::-1][:top_k]
    out = []
    for local_i in order:
        if sims[local_i] <= 0:
            continue
        global_i = idx[local_i]
        out.append((sims[local_i], chunks_df.iloc[global_i]))
    return out


