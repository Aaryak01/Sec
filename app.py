def risk_tone_summary(company: str, grouped: pd.DataFrame) -> str:
    """Template summary: peak, most recent reading, and the overall direction."""
    name = COMPANY_DISPLAY.get(company, company.capitalize())

    peak_row = grouped.loc[grouped["score"].idxmax()]
    latest_row = grouped.iloc[-1]

    sentence = (
        f"{name}'s risk language intensity peaked at {peak_row['score']:+.1f} in "
        f"{peak_row['date'].date()}"
    )
    if peak_row["date"] != grouped.iloc[0]["date"]:
        earliest_row = grouped.iloc[0]
        sentence += f", up from {earliest_row['score']:+.1f} in {earliest_row['date'].date()}"
    sentence += "."

    if len(grouped) > 1:
        prior_row = grouped.iloc[-2]
        delta = latest_row["score"] - prior_row["score"]
        if delta > 1:
            direction = "increasing"
        elif delta < -1:
            direction = "decreasing"
        else:
            direction = "stable"
        sentence += (
            f" The most recent filing ({latest_row['date'].date()}) shows a score of "
            f"{latest_row['score']:+.1f}, suggesting {direction} concern."
        )
    else:
        sentence += " That's the only filing I have data for."

    sentence += (
        " Rising intensity can mean genuinely new pressures, but it's often just "
        "more cautious legal language — the more useful signal is usually "
        "whether the risks themselves are new or repeated from prior filings, "
        "not just the tone."
    )
    return sentence


